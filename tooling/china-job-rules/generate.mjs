import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../../", import.meta.url);
const library = new URL("knowledge/china-job-rules/", root);
await import(new URL("validate.mjs", library).href);
if (process.exitCode) throw new Error("Invalid China job rules library");

const readJson = async (name) => JSON.parse(await readFile(new URL(name, library), "utf8"));
const roles = await readJson("roles.json");
const sources = await readJson("sources.json");
const rules = (await readFile(new URL("rules.jsonl", library), "utf8"))
	.split(/\r?\n/)
	.filter((line) => line.trim())
	.map((line) => JSON.parse(line));
if (roles.version !== sources.version) throw new Error("Library versions differ");
const snapshot = `// Generated by pnpm knowledge:generate. Edit knowledge/china-job-rules instead.\nimport type { ChinaKnowledge } from "./types";\n\nexport const CHINA_JOB_KNOWLEDGE: ChinaKnowledge = ${JSON.stringify(
	{
		version: roles.version,
		lastReviewed: roles.lastReviewed,
		methodology: roles.methodology,
		roles: roles.roles,
		rules,
		sources: sources.sources,
	},
	null,
	"\t",
)};\n`;
const target = new URL("packages/resume/src/china-job-rules/snapshot.ts", root);
if (process.argv.includes("--check")) {
	if ((await readFile(target, "utf8")) !== snapshot) {
		throw new Error("China rules snapshot is stale. Run pnpm knowledge:generate.");
	}
	console.log("China rules snapshot matches its source.");
} else {
	await writeFile(target, snapshot, "utf8");
}
